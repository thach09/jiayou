-- Schema only. Restoring continuity never inserts learning activity or rewards.
CREATE TABLE streak_restorations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request_key VARCHAR(36) NOT NULL,
    gap_token VARCHAR(64) NOT NULL,
    charge_month DATE NOT NULL CHECK (EXTRACT(DAY FROM charge_month) = 1),
    restored_count INTEGER NOT NULL CHECK (restored_count BETWEEN 1 AND 5),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_streak_restore_request UNIQUE (user_id, request_key),
    CONSTRAINT uk_streak_restore_owner_month UNIQUE (id, user_id, charge_month)
);
CREATE TABLE streak_restored_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    restoration_id BIGINT NOT NULL,
    restored_date DATE NOT NULL,
    charge_month DATE NOT NULL CHECK (EXTRACT(DAY FROM charge_month) = 1),
    credit_slot INTEGER NOT NULL CHECK (credit_slot BETWEEN 1 AND 5),
    CONSTRAINT fk_streak_restore_owner FOREIGN KEY (restoration_id, user_id, charge_month)
        REFERENCES streak_restorations(id, user_id, charge_month) ON DELETE CASCADE,
    CONSTRAINT uk_streak_restored_date UNIQUE (user_id, restored_date),
    CONSTRAINT uk_streak_month_credit UNIQUE (user_id, charge_month, credit_slot)
);
CREATE INDEX idx_streak_restored_user_date ON streak_restored_days(user_id, restored_date);
